// Helper functions for easy querying
export function findProductBySku(sku: string): MasterCatalogProduct | undefined {
  const clean = sku.trim().toUpperCase();
  return FSGOD_MASTER_CATALOG.find(p => p.sku.toUpperCase() === clean);
}

export function searchCatalog(query: string): MasterCatalogProduct[] {
  const q = query.toLowerCase().trim();
  if (!q) return FSGOD_MASTER_CATALOG;
  return FSGOD_MASTER_CATALOG.filter(p => 
    p.sku.toLowerCase().includes(q) ||
    p.name.toLowerCase().includes(q) ||
    p.categoryLabel.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.colors.some(c => c.toLowerCase().includes(q))
  );
}

export function formatCopCurrency(amount: number): string {
  return new Intl.NumberFormat('es-CO', {
    style: 'currency',
    currency: 'COP',
    maximumFractionDigits: 0,
  }).format(amount);
}

export function formatUsdCurrency(amount: number): string {
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(amount);
}
